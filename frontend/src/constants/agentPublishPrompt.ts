export function agentPublishPrompt({
  apiOrigin,
  key,
  site,
  projectId,
}: {
  apiOrigin: string;
  key: string;
  site: string;
  projectId: string | null;
}) {
  const action = projectId
    ? `更新 ${site} 的作品 ${projectId}。先读取 ${apiOrigin}/api/projects/${encodeURIComponent(site)}/${encodeURIComponent(projectId)}，仅提交需要更新的字段。`
    : `为 ${site} 创建一个新的公开作品。请在本轮实际发布。`;

  return `请阅读当前工作区的项目，把它整理成一篇可公开展示的 PanelShow 作品。 ${action}

接口规范：${apiOrigin}/api/agent/v1/schema
发布 API：${apiOrigin}
本次发布密钥：${key}

### 1. 找到能代表项目的体验

阅读 README、依赖清单、应用入口、关键组件、服务端实现、测试和部署配置。找到线上演示或运行本地版本，实际操作至少一条完整路径。遇到动画、播放、实时同步、数据流或复杂编辑器时，进入实际交互界面，触发核心操作，观察前后状态并对照源码。记录每项亮点的入口、实现文件、可观察结果和适合公开展示的素材。若工作区有多个独立项目且意图不明，先确认目标。

### 2. 写一篇工程案例

一句话简介说明谁能用它做成什么。中文正文建议有 2,500–4,500 个可见字符，按项目定位、典型操作、核心体验、实现机制、验证和现有边界分节。复杂项目可以更长。可参照 zkeq 的 LIVE ROOM、Self Music 等作品如何把产品操作、关键数据和技术决策讲成一个完整案例。重点解释输入如何转换成可见结果、关键状态由谁维护，以及遇到失败如何降级或恢复。用 Mermaid 表达真实的架构、时序或状态流。用已实现与已验证的事实支撑结论，未实际执行的测试只描述覆盖范围。

### 3. 填满 24 项概览并规划展示位

overview 必须是 24 个不同的 label/value 键值项。这里填写技术栈、组件库、渲染方案、架构、数据存储、处理流程、发布形态和已验证能力等短信息。tags 另作主题分类。把最能概括项目、适合扫读的 4 项放第 1–4 位；把帮助理解关键实现的 4 项放第 5–8 位；其余可核实细节放第 9–24 位。首页显示前 4 项，详情侧栏显示前 8 项，详情概览显示全部 24 项。内容不足时继续读代码、测试和配置，或询问缺失信息，确保 24 项各自提供不同事实。

### 4. 为亮点准备可验证的截图和演示

选择 3–6 个有区分度的亮点，把核心体验排第一。每个可视化亮点准备 4–6 张真实截图，覆盖入口、关键动作、中间或边界状态、完成结果；需要时加入桌面和手机各一张。动态效果拍摄至少两个可辨别的实际时刻，并在说明里标出触发动作和变化。优先实拍已加载的线上页面或本地可运行版本。图集首图使用核心功能的最佳画面，概览和亮点可引用同一份素材，但单个亮点的截图要各有用途。为每张图提供便于扫读的 title 和描述确切状态的 caption，并将 demo_url 指向可直接体验该亮点的公开页面。检查截图与正文中的敏感内容。纯后端或命令行项目可用可核实的终端、API 输出或监控画面作为证据。

### 5. 校验、发布并回读

预审正文、24 项概览顺序、首页与侧栏的字段选择、每个亮点的截图数量、封面和演示地址；关键证据缺失时先获取素材，再提交。读取接口规范，用 multipart 的 file 字段上传素材，把 asset_id 填到对应位置。SK 仅作为 Authorization 请求头中的 Bearer 凭证发送给指定发布 API，明文只用于本次请求。为发布请求选择稳定的 Idempotency-Key，超时后用原键和原内容重试。发布后打开公开详情与重点演示，并核对截图可访问、概览数量正确、玩法和实现的描述与实际画面一致。最后交付项目名、公开链接、亮点与各自截图数，以及尚待验证的事项。`;
}
