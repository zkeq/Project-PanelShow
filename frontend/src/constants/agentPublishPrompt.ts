export function agentPublishPrompt({
  apiOrigin,
  key,
  site,
  projectId,
}: {
  apiOrigin: string;
  key: string;
  site: string;
  projectId: string | null;
}) {
  const action = projectId
    ? `更新 ${site} 的作品 ${projectId}。先读取 ${apiOrigin}/api/projects/${encodeURIComponent(site)}/${encodeURIComponent(projectId)}，仅提交需要更新的字段。`
    : `为 ${site} 创建一个新的公开作品。请在本轮实际发布。`;

  return `请阅读当前工作区的项目，把它整理成一篇可公开展示的 PanelShow 作品。 ${action}

接口规范：${apiOrigin}/api/agent/v1/schema
发布 API：${apiOrigin}
本次发布密钥：${key}

### 1. 找到能代表项目的体验

阅读 README、依赖清单、应用入口、关键组件、服务端实现、测试和部署配置。找到线上演示或运行本地版本，实际操作至少一条完整路径。遇到动画、播放、实时同步、数据流或复杂编辑器时，进入实际交互界面，触发核心操作，观察前后状态并对照源码。记录每项亮点的入口、实现文件、可观察结果和适合公开展示的素材。若工作区有多个独立项目且意图不明，先确认目标。

### 2. 写一份可扫读的作品说明

一句话简介说明项目做了什么。正文面向浏览作品集的人，先给最值得看的实现，再用短标题、列表和短段落交代关键技术、机制、取舍与可见结果。根据项目选择栏目，例如渲染、数据、部署、交互或工程实践。每段回答一个具体问题，保留高信号细节，省略背景故事、泛泛总结和重复描述。需要解释复杂链路时可用一张简洁的 Mermaid 图。用已实现与已验证的事实支撑结论，未执行的测试只描述覆盖范围。

### 3. 填满 24 项概览并规划展示位

overview 必须是 24 个不同的项，每项填写 label、简短静态 value 和语义对应的 icon。用接口规范中的 Iconify 官方集合、图标清单或搜索链接查询，每项从官方结果自己选择并填写完整的「图标集:图标名」。亮点也可按同样方式填写 icon。tags 另作主题分类。把最能概括项目的 4 项放第 1–4 位，帮助理解关键实现的 4 项放第 5–8 位，其余可核实细节放第 9–24 位。首页显示前 4 项，详情侧栏显示前 8 项，详情概览显示全部 24 项。内容不足时继续读代码、测试和配置，确保每项都提供不同事实。

### 4. 为亮点准备可验证的截图和演示

选择 3–6 个有区分度的亮点，把核心体验排第一。有截图能力时，每个可视化亮点准备 4–6 张真实画面，覆盖关键动作和不同状态。桌面默认输出 2560×1440，移动端保持原比例，长边目标 2560 像素。每次截图前等内容、字体和可见图片加载完成，确认没有骨架屏、裂图或空白；动态效果应拍摄至少两个可辨别的实际时刻。首张主图是封面，为每张图提供简短 title 和说明确切状态的 caption。demo_url 指向可直接体验的页面。检查截图和正文中的敏感内容。没有截图能力时跳过截图字段，继续完成其余内容并在交付时说明。

### 5. 校验、发布并回读

预审正文可读性、24 项概览顺序和图标、演示链接，以及已提供截图的尺寸、加载状态和覆盖范围。有截图时用同一把 SK 和 multipart 的 file 字段上传，把 asset_id 填到对应位置。SK 仅作为 Authorization 请求头中的 Bearer 凭证发送给指定发布 API。为发布请求选择稳定的 Idempotency-Key，超时后用原键和原内容重试。提交后打开公开详情与重点演示，核对介绍、图标和实际效果。最后交付项目名、公开链接、亮点与各自截图数，以及尚待验证的事项。`;
}
